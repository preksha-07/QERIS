"""
QERIS S2: Cloud Service API and Persistent Telemetry Storage

Provides the Cloud Telemetry API and persistent SQLite database for the QERIS architecture.
Demonstrates:
Device -> Protected Session -> Gateway -> Gateway-to-Cloud TLS/HTTP -> Cloud Storage.
Flow segregation and policy-derived sensitivity classifications are preserved in storage.
"""
from __future__ import annotations

import json
import sqlite3
import time
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Optional

from fastapi import FastAPI, HTTPException, Query, Request, Response, status
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from qeris.s2.config import DEFAULT_CLOUD_DB_PATH

cloud_app = FastAPI(
    title="QERIS Cloud Telemetry Service",
    version="1.0.0",
    description="Backend cloud service ingesting and storing sensitivity-segregated telemetry from QERIS Gateways.",
)

cloud_app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Standard ASGI application entrypoint alias for uvicorn/Docker
app = cloud_app


class TelemetryIngestModel(BaseModel):
    event_id: str = Field(..., description="Unique event identifier generated by device or gateway")
    device_id: str = Field(..., description="Originating IoT device identifier")
    flow_id: str = Field(..., description="Flow identifier")
    timestamp: float = Field(..., description="Timestamp of telemetry creation")
    sensitivity: str = Field(..., description="Sensitivity tier derived from verified gateway policy")
    security_profile: str = Field(..., description="Security profile under which session was protected")
    policy_version: int = Field(..., description="Applicable gateway policy version")
    policy_digest: str = Field(..., description="Applicable gateway policy digest")
    payload: Any = Field(..., description="Decrypted payload content or reference")
    gateway_decision: str = Field(default="ALLOW", description="Gateway decision authorizing this message")


class CloudDatabase:
    """Persistent SQLite database storing telemetry received from gateways."""

    def __init__(self, db_path: str = DEFAULT_CLOUD_DB_PATH):
        self.db_path = db_path
        self._init_db()

    @contextmanager
    def _get_connection(self):
        conn = sqlite3.connect(self.db_path, timeout=10.0, isolation_level=None)
        conn.row_factory = sqlite3.Row
        try:
            yield conn
        finally:
            conn.close()

    def _init_db(self) -> None:
        Path(self.db_path).parent.mkdir(parents=True, exist_ok=True)
        with self._get_connection() as conn:
            conn.execute("PRAGMA journal_mode = WAL")
            conn.execute("PRAGMA synchronous = NORMAL")
            conn.execute("""
                CREATE TABLE IF NOT EXISTS cloud_telemetry (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    event_id TEXT UNIQUE NOT NULL,
                    device_id TEXT NOT NULL,
                    flow_id TEXT NOT NULL,
                    timestamp REAL NOT NULL,
                    sensitivity TEXT NOT NULL,
                    security_profile TEXT NOT NULL,
                    policy_version INTEGER NOT NULL,
                    policy_digest TEXT NOT NULL,
                    payload TEXT NOT NULL,
                    gateway_decision TEXT NOT NULL,
                    received_at REAL NOT NULL
                )
            """)
            conn.execute("CREATE INDEX IF NOT EXISTS idx_telemetry_flow ON cloud_telemetry(flow_id)")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_telemetry_device ON cloud_telemetry(device_id)")
            conn.execute("CREATE INDEX IF NOT EXISTS idx_telemetry_sens ON cloud_telemetry(sensitivity)")

    def store_telemetry(self, item: TelemetryIngestModel) -> bool:
        now = time.time()
        payload_str = json.dumps(item.payload) if not isinstance(item.payload, str) else item.payload
        try:
            with self._get_connection() as conn:
                conn.execute(
                    """
                    INSERT INTO cloud_telemetry (
                        event_id, device_id, flow_id, timestamp, sensitivity,
                        security_profile, policy_version, policy_digest, payload,
                        gateway_decision, received_at
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    ON CONFLICT(event_id) DO UPDATE SET
                        received_at = excluded.received_at
                    """,
                    (
                        item.event_id,
                        item.device_id,
                        item.flow_id,
                        item.timestamp,
                        item.sensitivity,
                        item.security_profile,
                        item.policy_version,
                        item.policy_digest,
                        payload_str,
                        item.gateway_decision,
                        now,
                    ),
                )
            return True
        except Exception:
            return False

    def get_telemetry(
        self,
        device_id: Optional[str] = None,
        flow_id: Optional[str] = None,
        sensitivity: Optional[str] = None,
        since: Optional[float] = None,
        limit: int = 100,
    ) -> list[dict[str, Any]]:
        query = "SELECT * FROM cloud_telemetry WHERE 1=1"
        params: list[Any] = []

        if device_id:
            query += " AND device_id = ?"
            params.append(device_id)
        if flow_id:
            query += " AND flow_id = ?"
            params.append(flow_id)
        if sensitivity:
            query += " AND sensitivity = ?"
            params.append(sensitivity)
        if since is not None:
            query += " AND received_at >= ?"
            params.append(since)

        query += " ORDER BY received_at DESC LIMIT ?"
        params.append(limit)

        with self._get_connection() as conn:
            cursor = conn.execute(query, params)
            results = []
            for row in cursor.fetchall():
                d = dict(row)
                try:
                    d["payload"] = json.loads(d["payload"])
                except Exception:
                    pass
                results.append(d)
            return results

    def get_by_event_id(self, event_id: str) -> Optional[dict[str, Any]]:
        with self._get_connection() as conn:
            cursor = conn.execute("SELECT * FROM cloud_telemetry WHERE event_id = ?", (event_id,))
            row = cursor.fetchone()
            if not row:
                return None
            d = dict(row)
            try:
                d["payload"] = json.loads(d["payload"])
            except Exception:
                pass
            return d

    def get_stats(self) -> dict[str, Any]:
        with self._get_connection() as conn:
            cursor = conn.execute("""
                SELECT flow_id, sensitivity, COUNT(*) as count
                FROM cloud_telemetry
                GROUP BY flow_id, sensitivity
            """)
            breakdown = [dict(row) for row in cursor.fetchall()]

            total_cursor = conn.execute("SELECT COUNT(*) as total FROM cloud_telemetry")
            total = total_cursor.fetchone()["total"]

            return {
                "total_records": total,
                "breakdown": breakdown,
            }

    def clear(self) -> None:
        with self._get_connection() as conn:
            conn.execute("DELETE FROM cloud_telemetry")


# Global Database Instance for Cloud App
_cloud_db = CloudDatabase()


def get_cloud_db() -> CloudDatabase:
    """Returns the active cloud database instance (allowing per-app test overrides)."""
    return getattr(cloud_app.state, "db", _cloud_db)


def set_cloud_db(db: CloudDatabase) -> None:
    """Sets a custom cloud database instance on the cloud app."""
    cloud_app.state.db = db


@cloud_app.post("/api/v1/cloud/ingest", status_code=status.HTTP_201_CREATED)
def ingest_telemetry(item: TelemetryIngestModel):
    db = get_cloud_db()
    success = db.store_telemetry(item)
    if not success:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to persist telemetry in cloud database",
        )
    return {
        "status": "STORED",
        "event_id": item.event_id,
        "flow_id": item.flow_id,
        "sensitivity": item.sensitivity,
        "stored_at": time.time(),
    }


@cloud_app.get("/api/v1/cloud/telemetry")
def query_telemetry(
    device_id: Optional[str] = Query(None),
    flow_id: Optional[str] = Query(None),
    sensitivity: Optional[str] = Query(None),
    since: Optional[float] = Query(None),
    limit: int = Query(100, ge=1, le=1000),
):
    db = get_cloud_db()
    records = db.get_telemetry(
        device_id=device_id,
        flow_id=flow_id,
        sensitivity=sensitivity,
        since=since,
        limit=limit,
    )
    return {
        "count": len(records),
        "records": records,
    }


@cloud_app.get("/api/v1/cloud/telemetry/{event_id}")
def get_single_telemetry(event_id: str):
    db = get_cloud_db()
    record = db.get_by_event_id(event_id)
    if not record:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Event ID not found")
    return record


@cloud_app.get("/api/v1/cloud/stats")
def get_cloud_stats():
    db = get_cloud_db()
    return db.get_stats()


@cloud_app.get("/api/v1/cloud/health")
def cloud_health():
    db = get_cloud_db()
    stats = db.get_stats()
    return {
        "status": "UP",
        "service": "QERIS Cloud Telemetry Service",
        "total_records": stats["total_records"],
    }


@cloud_app.post("/api/v1/cloud/reset")
def reset_cloud(request: Request):
    """
    Clears all telemetry records from cloud database for test and experiment isolation.
    Protected by administrative API key authentication (QERIS_ADMIN_API_KEY).
    - Unconfigured key: HTTP 403 Forbidden (fail-secure shutdown)
    - Configured but missing/invalid key: HTTP 401 Unauthorized
    - Valid key: HTTP 200 OK
    """
    import os
    expected_key = os.environ.get("QERIS_ADMIN_API_KEY")
    if not expected_key:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Forbidden: Cloud reset access is disabled because no admin API key is configured",
        )
    admin_hdr = request.headers.get("X-Admin-Key")
    auth_hdr = request.headers.get("Authorization")
    is_authorized = (
        admin_hdr == expected_key
        or auth_hdr == f"Bearer {expected_key}"
        or auth_hdr == expected_key
    )
    if not is_authorized:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Unauthorized: Invalid or missing admin API key",
        )
    db = get_cloud_db()
    db.clear()
    return {"status": "RESET_COMPLETED", "service": "QERIS Cloud Telemetry Service"}


def run_cloud_service(
    host: str = "127.0.0.1",
    port: int = 8001,
    use_tls: bool = True,
    ssl_certfile: Optional[str] = None,
    ssl_keyfile: Optional[str] = None,
):
    """Launches Cloud Telemetry Service with optional TLS support."""
    import uvicorn
    from qeris.s2.certs import ensure_cloud_tls_certs

    cert_path, key_path = ensure_cloud_tls_certs()
    cert_str = ssl_certfile or str(cert_path)
    key_str = ssl_keyfile or str(key_path)

    if use_tls:
        uvicorn.run(
            "qeris.s2.cloud_service:app",
            host=host,
            port=port,
            ssl_certfile=cert_str,
            ssl_keyfile=key_str,
        )
    else:
        uvicorn.run(
            "qeris.s2.cloud_service:app",
            host=host,
            port=port,
        )

